def step_manifest():
    """Run manifest: code revision, environment, and SHA-256 of every committed Week 19 output file."""
    import hashlib
    import platform
    import subprocess
    import importlib.metadata as md
    files = sorted(p for p in OUT.rglob("*") if p.is_file() and "_cache" not in p.parts and p.name not in ("RUN_MANIFEST.json", "full_run_log.txt"))
    rows = [{"path": str(p.relative_to(OUT.parent.parent)).replace("\\", "/"), "bytes": p.stat().st_size,
             "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in files]
    head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, cwd=OUT.parent.parent).stdout.strip()
    branch = subprocess.run(["git", "rev-parse", "--abbrev-ref", "HEAD"], capture_output=True, text=True, cwd=OUT.parent.parent).stdout.strip()
    man = {"generated_by": "python -m src.week19_temporal_audit all", "code_base_commit": head, "branch": branch,
           "python": platform.python_version(), "packages": {k: md.version(k) for k in ("numpy", "pandas", "scipy", "scikit-learn", "matplotlib", "huggingface_hub")},
           "pins": {"OLD": OLD_REV, "OLD_audit_pin_reused_bytes": "d69dac5bda8b622bc0de316b112815c6056c06ec", "NEW": NEW_REV},
           "outputs": rows}
    (OUT / "provenance" / "RUN_MANIFEST.json").write_text(json.dumps(man, indent=1))
    return man


