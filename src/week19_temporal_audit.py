def frame_intervals(tf):
    """Midpoint (frame-centred) intervals for sorted frame times; the first/last frame interval is clipped at its own time."""
    tf = np.asarray(tf, float)
    if len(tf) < 2:
        return np.zeros(len(tf))
    mid = 0.5 * (tf[1:] + tf[:-1])
    return np.r_[mid, tf[-1]] - np.r_[tf[0], mid]


def _switch_location(t_from, t_to, row):
    cut, ex, last_f = row["active_cutoff_ms"], row["derived_exit_ms"], row["last_F_ms"]
    if not (np.isfinite(t_from) and np.isfinite(t_to)):
        return "timing_unavailable"
    if np.isfinite(last_f) and t_to <= last_f:
        return "overlaps_forming_labels"          # Forming Phase frames still occur at or after the new regime frame
    if np.isfinite(cut) and t_to <= cut:
        return "established_active_window"
    if np.isfinite(cut) and t_from >= cut:
        return "late_after_derived_exit" if (np.isfinite(ex) and t_from >= ex) else "late_after_active_cutoff"
    return "straddles_active_cutoff" if np.isfinite(cut) else "window_unavailable"


def timed_tables(frames, fmap, ser, epis):
    """K runs and active-regime switches with monitor times; time-weighted K fractions (midpoint rule)."""
    fm = fmap.merge(frames[["sim_id", "frame_pos", "campaign"]], on=["sim_id", "frame_pos"], how="left")
    S = ser.set_index("sim_id")
    tmap = {sid: g.sort_values("frame_pos") for sid, g in fm.groupby("sim_id")}
    ep = epis.copy()
    starts, ends, lo, hi = [], [], [], []
    for r in ep.itertuples(index=False):
        tf = tmap[r.sim_id].time_ms.to_numpy(); n = len(tf)
        starts.append(tf[r.start_pos]); ends.append(tf[r.end_pos])
        lo.append(tf[r.start_pos - 1] if r.start_pos > 0 else np.nan); hi.append(tf[r.end_pos + 1] if r.end_pos + 1 < n else np.nan)
    ep["start_ms"], ep["end_ms"], ep["bracket_lo_ms"], ep["bracket_hi_ms"] = starts, ends, lo, hi
    ep["observed_duration_ms"] = ep.end_ms - ep.start_ms                  # first-to-last labelled K frame, no extrapolation
    ep["bracketed_max_duration_ms"] = ep.bracket_hi_ms - ep.bracket_lo_ms  # upper bound between the neighbouring non-K frames
    ep = ep.merge(S[["derived_exit_ms", "active_cutoff_ms", "first_SS_ms", "last_F_ms"]], left_on="sim_id", right_index=True, how="left")
    ep["start_over_exit"] = ep.start_ms / ep.derived_exit_ms; ep["end_over_exit"] = ep.end_ms / ep.derived_exit_ms
    trans, extra = [], []
    for sid, g in tmap.items():
        codes = g.code.to_numpy(); tf = g.time_ms.to_numpy(); pos = g.frame_pos.to_numpy()
        act = np.flatnonzero(np.isin(codes, ["C", "K"]))
        row = S.loc[sid] if sid in S.index else pd.Series({"active_cutoff_ms": np.nan, "derived_exit_ms": np.nan, "last_F_ms": np.nan, "first_SS_ms": np.nan})
        for a, b in zip(act[:-1], act[1:]):
            if codes[a] == codes[b]:
                continue
            mid = codes[a + 1:b]
            ex = row["derived_exit_ms"]; ss = row["first_SS_ms"]
            trans.append({"sim_id": sid, "campaign": g.campaign.iloc[0], "type": f"{codes[a]}_to_{codes[b]}",
                          "from_pos": int(pos[a]), "to_pos": int(pos[b]), "from_ms": tf[a], "to_ms": tf[b],
                          "bracket_width_ms": tf[b] - tf[a], "intermediate_labels": "+".join(sorted(set(mid))) if len(mid) else "none",
                          "location": _switch_location(tf[a], tf[b], row), "from_over_exit": tf[a] / ex if np.isfinite(ex) else np.nan,
                          "after_first_scanning_stopped": int(bool(np.isfinite(ss) and tf[a] >= ss))})
        ok = np.isfinite(tf)
        w = np.zeros(len(tf)); w[ok] = frame_intervals(tf[ok])
        kc = np.isin(codes, ["C", "K"]); fck = np.isin(codes, ["F", "C", "K"])
        extra.append({"sim_id": sid,
                      "K_time_frac_FCK_midpoint": w[codes == "K"].sum() / w[fck].sum() if w[fck].sum() > 0 else np.nan,
                      "K_time_frac_KC_midpoint": w[codes == "K"].sum() / w[kc].sum() if w[kc].sum() > 0 else np.nan,
                      "FCK_time_covered_ms": w[fck].sum(),
                      "active_span_first_to_last_CK_ms": (tf[act[-1]] - tf[act[0]]) if (len(act) and ok[act].all()) else np.nan,
                      "frames_with_time": int(ok.sum())})
    return ep, pd.DataFrame(trans), pd.DataFrame(extra)


def record_flags(r):
    f = []
    if r.get("bounds_time_rows_match", 1) == 0:
        f.append("bounds_time_row_mismatch")
    if r.get("recording_ends_before_90pct_domain", 0) == 1:
        f.append("recording_ends_before_90pct_domain")
    if r.get("timing_mapping_ok", 1) != 1:
        f.append("frame_timing_unmappable")
    if r["descriptor"] in ("forming_only", "no_physical_label"):
        f.append("no_active_regime_label")
    if r.get("F_after_active_onset", 0) == 1:
        f.append("F_after_active_onset")
    if r.get("IE_after_physical_onset", 0) == 1:
        f.append("IE_after_physical_onset")
    if r.get("max_depth_whole_is_last_row", 0) == 1:
        f.append("max_depth_in_last_row")
    if min(r.get("frames_csv_rows_match_ledger", 1), r.get("frames_csv_timesteps_match_ledger", 1), r.get("frames_csv_labels_match_label_final", 1)) == 0:
        f.append("frames_csv_ledger_disagreement")
    return ";".join(f)


