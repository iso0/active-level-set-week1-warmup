def u_reference():
    """Recover the OLD max-depth reference threshold from the existing rules (OLD data only)."""
    from sklearn.linear_model import LogisticRegression
    pop = pd.read_csv(POPULATION, usecols=["experiment_name", "has_keyhole", "max_depth_um"])
    y = pop.has_keyhole.map({True: 1, False: 0, "True": 1, "False": 0}).astype(int).to_numpy()
    d = pop.max_depth_um.to_numpy(float); t = np.log(d)
    kh, nk = t[y == 1], t[y == 0]
    rec = {"source": "outputs/week7_06_real_data_boundary_active_level_set/primary_common_population.csv (max_depth_um, has_keyhole)",
           "n_old": int(len(y)), "n_keyhole": int(y.sum()),
           "min_keyhole_max_depth_um": float(np.exp(kh.min())), "max_nonkeyhole_max_depth_um": float(np.exp(nk.max())),
           "separable": bool(nk.max() < kh.min())}
    if rec["separable"]:
        u = float(np.exp(.5 * (nk.max() + kh.min()))); rule = "midpoint of the separated log-depth gap"
    else:
        lr = LogisticRegression(C=1e6, max_iter=5000).fit(t[:, None], y)
        u = float(np.exp(-lr.intercept_[0] / lr.coef_[0, 0])); rule = "1-D logistic regression on log depth (C=1e6), the non-separable branch"
    rec.update({"u_ref_um": u, "rule": f"E1 learned-threshold procedure (src/week18_engine.py::DepthGPR.fit) applied to all 405 OLD runs: {rule}",
                "engine_default_um": 111.0, "week18_count_rule_um": 111.2})
    # descriptive single-threshold BA on OLD (oracle on OLD itself; context only)
    cand = np.unique(d)
    best = max(((0.5 * ((d[y == 1] >= c).mean() + (d[y == 0] < c).mean()), c) for c in cand))
    rec["old_best_single_threshold_BA"] = float(best[0]); rec["old_best_single_threshold_um"] = float(best[1])
    for name, c in [("u_ref", u), ("111.0", 111.0), ("111.2", 111.2)]:
        rec[f"old_BA_at_{name}"] = float(0.5 * ((d[y == 1] >= c).mean() + (d[y == 0] < c).mean()))
    return rec


