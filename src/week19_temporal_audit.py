def representative_selection(reg, cases):
    """Deterministic: per (campaign, descriptor) the run whose K/(F+C+K) is closest to the group median (VX median for
    conduction-only), among runs with exact timing and aligned bounds; plus the verified matched NEW pair."""
    ok = reg[(reg.timing_mapping_ok == 1) & (reg.bounds_time_rows_match == 1)]
    pick = []
    for camp, desc, role in [("OLD", "K_then_C__no_later_K", "K then C, no later K"), ("NEW", "K_then_C__no_later_K", "K then C, no later K"),
                             ("OLD", "alternating__terminal_C", "alternating (C between K blocks)"), ("NEW", "alternating__terminal_C", "alternating (C between K blocks)"),
                             ("OLD", "keyhole_only__K_at_end", "K ongoing at observation end"), ("NEW", "C_then_K__K_at_end", "K ongoing at observation end"),
                             ("OLD", "conduction_only", "Conduction only")]:
        g = ok[(ok.campaign == camp) & (ok.descriptor == desc)]
        if not len(g):
            g = ok[(ok.campaign == camp) & ok.descriptor.str.startswith(desc.split("__")[0])]
        if not len(g):
            continue
        key = "VX" if desc == "conduction_only" else "frac_K_FCK"
        j = (g[key] - g[key].median()).abs().sort_values(kind="stable").index[0]
        pick.append({"sim_id": g.loc[j, "sim_id"], "role": role, "rule": f"closest to the {camp} {desc} median of {key} (n={len(g)})"})
    for h, role in [("P-387p361336282_VX-0p960187357846_LS-4p72484046084e-05_ST-390p52586458_M-TI64_XI-0p0002_XF-0p0014_XL-0p0012_TE-0p0021_DT-5p02414509376e-06_H-b302fc6cbd", "matched pair: NEW has_keyhole=0"),
                    ("P-380p041479483_VX-0p952843483906_LS-4p56527036263e-05_ST-376p177191048_M-TI64_XI-0p0002_XF-0p0014_XL-0p0012_TE-0p0021_DT-5p0628678104e-06_H-b7e3ed2e12", "matched pair: NEW has_keyhole=1")]:
        pick.append({"sim_id": h, "role": role, "rule": "brief-named pair, verified by full name (the H suffix b302fc6cbd is shared by two NEW runs)"})
    sel = pd.DataFrame(pick).drop_duplicates("sim_id")
    _w(sel.merge(reg[["sim_id", "campaign", "descriptor", "collapsed_sequence", "P", "VX", "LS_um_radius", "ST", "frac_K_FCK", "frac_K_KC"]], on="sim_id"),
       "representative_cases.csv")
    return sel


